"""Export unmodified PS4 workstation sprites and their authored scene transforms.

Input: files extracted at media-index.json byte offsets from mcps4 MediaOrbis.arc.
No layout coordinates or replacement artwork are generated by this exporter.
"""
import argparse
import hashlib
import json
import struct
from io import BytesIO
from pathlib import Path

from PIL import Image
from read_fui import Fui
from read_languages import read_languages
from read_block_constructors import Source


def sha(data):
    return hashlib.sha256(data).hexdigest()


def rgba(data):
    source = Image.open(BytesIO(data)).convert('RGBA')
    b, g, r, a = source.split()
    output = BytesIO()
    Image.merge('RGBA', (r, g, b, a)).save(output, format='PNG')
    return output.getvalue()


def export(input_dir, project, eboot):
    graphics = Fui(input_dir / 'skinHDGraphicsInGame.fui')
    widgets = Fui(input_dir / 'skinHDInGame.fui')
    assets = project / 'src/main/resources/assets/legacyconsole'
    textures = assets / 'textures/ps4/workstations'
    textures.mkdir(parents=True, exist_ok=True)
    data = dict(repository='Nejirus/mcps4',
                revision='37e258085773f11599cf0ffe29119926769554b7',
                channel_conversion='BGRA to RGBA; no other pixel changes',
                graphics_sha256=sha(graphics.b), widgets_sha256=sha(widgets.b),
                sprites={}, panels={}, scenes={}, widgets={})
    labels = Fui(input_dir / 'skinHDGraphicsLabels.fui')
    kind, index = labels.exports['FJ_LabelBlack']
    definition = labels.defs[index]
    node = labels.geometry[labels.frames[definition[1]]['start']]
    assert node['header'][1] & 255 == 5
    data['label'] = labels.textfields[node['header'][3]]
    data['label']['matrix'] = node['matrix']
    for field, symbol in [('centered_label','FJ_Label_Black_Centered')]:
        definition=labels.defs[labels.exports[symbol][1]]
        node=labels.geometry[labels.frames[definition[1]]['start']]
        data[field]=dict(labels.textfields[node['header'][3]],matrix=node['matrix'])
    data['labels_sha256'] = sha(labels.b)
    data['typography']={}
    definition=graphics.defs[graphics.exports['FJ_Label_Black_Small'][1]]
    node=graphics.geometry[graphics.frames[definition[1]]['start']]
    data['small_label']=dict(graphics.textfields[node['header'][3]],matrix=node['matrix'])
    for name in ['FJ_Label_Enchanting','FJ_Label_Enchanting_Inactive']:
        kind,index=graphics.exports[name]
        definition=graphics.defs[index]
        node=graphics.geometry[graphics.frames[definition[1]]['start']]
        assert node['header'][1]&255==5
        data['typography'][name]=graphics.textfields[node['header'][3]]
        data['typography'][name]['matrix']=node['matrix']
    raw_loc=(input_dir/'languages.loc').read_bytes()
    native_text=read_languages(raw_loc)['en-EN']
    keys=['a77592e8','a89a0b2f','2d955f51','7a2ef634','cc04e002','dcd3c648',
          'b3c82373','7b8c1d5d','ec992395','2fddc05c','21ae8965',
          '07960f18','1536049b','d279b4e2','e293078e','5a64e9bc',
          'f77d295e','14630b9e','80cf40eb']
    data['labels']={key:native_text[key] for key in keys}
    data['language_sha256']=sha(raw_loc)
    source=Source(eboot)
    words=source.read(0xee47b4,0x19d*2).decode('utf-16le')
    assert words.startswith('the elder scrolls ') and words.endswith(' baguette')
    name_data=dict(repository=data['repository'],revision=data['revision'],
                   eboot_sha256=sha(eboot.read_bytes()),constructor='0x009e1f90',
                   routine='0x009e1df0',word_address='0x00ee47b4',
                   word_bytes_sha256=sha(source.read(0xee47b4,0x19d*2)),words=words.split())
    (assets/'ps4_enchantment_names.json').write_text(json.dumps(name_data,indent=2)+'\n')

    # Keep every exported bitmap: names, sizes and hashes remain independently auditable.
    for name, (kind, index) in graphics.exports.items():
        if kind != 3:
            continue
        image = graphics.images[index]
        converted = rgba(image['bytes'])
        filename = name.lower()
        (textures / (filename + '.png')).write_bytes(converted)
        data['sprites'][name] = dict(texture=filename, size=image['size'],
                                    source_sha256=sha(image['bytes']), sha256=sha(converted))

    nd, nn, np, nsh, nb, nv, *_ = graphics.counts
    shapes = 0x98 + nd * 28 + np * 132
    batches = shapes + nsh * 28
    vertices = batches + nb * 44
    for name in ['FJ_Panel9Grid', 'FJ_SquareRecessedPanel', 'FJ_SquareRecessedPanelEnchant',
                 'FJ_PointerTextPanel']:
        kind, index = graphics.exports[name]
        assert kind == 2
        definition = graphics.defs[index]
        frame = graphics.frames[definition[1]]
        assert frame['count'] == 1
        node = graphics.geometry[frame['start']]
        assert node['header'][1] & 255 == 1
        shape = node['header'][3]
        _, first, count = struct.unpack_from('<3I', graphics.b, shapes + shape * 28)
        assert count == 9
        pieces = []
        for i in range(count):
            offset = batches + (first + i) * 44
            flags, _, bitmap = struct.unpack_from('<3I', graphics.b, offset)
            matrix = struct.unpack_from('<6f', graphics.b, offset + 12)
            first_vertex, vertex_count = struct.unpack_from('<2I', graphics.b, offset + 36)
            assert vertex_count == 6
            points = [struct.unpack_from('<2f', graphics.b, vertices + (first_vertex + j) * 8)
                      for j in range(vertex_count)]
            xs, ys = zip(*points)
            image = graphics.images[bitmap]
            converted = rgba(image['bytes'])
            filename = name.lower() + '_' + str(i)
            (textures / (filename + '.png')).write_bytes(converted)
            pieces.append(dict(texture=filename,
                               rect=[min(xs), min(ys), max(xs)-min(xs), max(ys)-min(ys)],
                               matrix=matrix, source_sha256=sha(image['bytes']), sha256=sha(converted)))
        grid = [struct.unpack('<f', struct.pack('<I', x))[0] for x in definition[5:9]]
        data['panels'][name] = dict(grid=grid, pieces=pieces)

    def nodes(fui, definition):
        d = fui.defs[definition]
        frame = fui.frames[d[1]]
        return fui.geometry[frame['start']:frame['start'] + frame['count']]

    for name in ['BrewingStandMenu', 'CartographyMenu', 'EnchantingMenu', 'BeaconMenu','TradingMenu']:
        fui = Fui(input_dir / (name + '1080.fui'))
        root = next(g for g in fui.geometry if g['name'] == 'MainPanel')
        controls, static = {}, []
        for node in nodes(fui, root['header'][3]):
            kind, index = node['header'][1] & 255, node['header'][3]
            if node['name'] == 'BackgroundPanel':
                background = nodes(fui, index)
                if not background: continue # Trading's background is a preceding unnamed import.
                assert len(background) == 1
                child = background[0]
                assert child['header'][1] & 255 == 4
                static.append(dict(symbol=fui.imports[child['header'][3]], matrix=child['matrix']))
            elif node['name']:
                controls[node['name']] = dict(matrix=node['matrix'],
                    symbol=fui.imports[index] if kind == 4 else 'local:' + str(index))
            elif kind == 4:
                static.append(dict(symbol=fui.imports[index], matrix=node['matrix']))
        data['scenes'][name] = dict(sha256=sha(fui.b), root=root['matrix'][4:],
                                   controls=controls, static=static)

    # Resolve nested original graphics display lists too. AnvilPlusSmall, used
    # by cartography, is a 7.7999878x display-list instance of the 5x5 AnvilPlus
    # bitmap, not an independently exported bitmap.
    def compose(a,b):
        return [a[0]*b[0]+a[2]*b[1],a[1]*b[0]+a[3]*b[1],
                a[0]*b[2]+a[2]*b[3],a[1]*b[2]+a[3]*b[3],
                a[0]*b[4]+a[2]*b[5]+a[4],a[1]*b[4]+a[3]*b[5]+a[5]]
    def expand_graphic(kind,index,matrix):
        if kind==3:
            symbol=next(k for k,v in graphics.exports.items() if v==(3,index))
            return [dict(symbol=symbol,matrix=matrix)]
        assert kind==2
        definition=graphics.defs[index];assert definition[2]==1
        frame=graphics.frames[definition[1]];result=[]
        for child in graphics.geometry[frame['start']:frame['start']+frame['count']]:
            result+=expand_graphic(child['header'][1]&255,child['header'][3],compose(matrix,child['matrix']))
        return result
    for scene in data['scenes'].values():
        expanded=[]
        for node in scene['static']:
            if node['symbol'] in data['panels'] or node['symbol'] in data['sprites']:expanded.append(node)
            else:expanded+=expand_graphic(*graphics.exports[node['symbol']],node['matrix'])
        scene['static']=expanded

    # Trading's selector/cross/arrow are named local display lists, not static
    # backgrounds. Preserve their nested graphics transforms for conditional draw.
    trading=Fui(input_dir/'TradingMenu1080.fui')
    objects={}
    for name in ['TradingSelector','RightArrow1','RedCross','PadLock']:
        parent=next(g for g in trading.geometry if g['name']==name)
        children=nodes(trading,parent['header'][3]); assert len(children)==1
        child=children[0]; assert child['header'][1]&255==4
        symbol=trading.imports[child['header'][3]]
        objects[name]=expand_graphic(*graphics.exports[symbol],compose(parent['matrix'],child['matrix']))
    data['scenes']['TradingMenu']['objects']=objects
    hud=Fui(input_dir/'skinHDHud.fui')
    hud_graphics=Fui(input_dir/'skinHDGraphicsHud.fui')
    experience=[]
    outer=data['scenes']['TradingMenu']['controls']['ExperienceBar']['matrix']
    for node in nodes(hud,hud.exports['fourj.ProgressBars.FJ_ExperienceBar'][1]):
        leaf=nodes(hud,node['header'][3]); assert len(leaf)==1
        leaf=leaf[0]; assert leaf['header'][1]&255==4
        symbol=hud.imports[leaf['header'][3]]
        image=hud_graphics.images[hud_graphics.exports[symbol][1]]
        converted=rgba(image['bytes']);filename=symbol.lower()
        (textures/(filename+'.png')).write_bytes(converted)
        data['sprites'][symbol]=dict(texture=filename,size=image['size'],
            source_sha256=sha(image['bytes']),sha256=sha(converted))
        experience.append(dict(name=node['name'],symbol=symbol,
            matrix=compose(outer,compose(node['matrix'],leaf['matrix']))))
    data['scenes']['TradingMenu']['experience']=experience
    data['scenes']['TradingMenu']['hud_sha256']=sha(hud.b)
    data['scenes']['TradingMenu']['hud_graphics_sha256']=sha(hud_graphics.b)

    # Preserve widget display-list frames, including remove records, for state-specific rendering.
    for name in ['FJ_BrewingArrow', 'FJ_BrewingBubbles', 'FJ_BrewingPlate',
                 'FJ_EnchantingButton_Normal', 'FJ_BeaconEffectButton_Normal', 'FJ_TextInput_Normal']:
        export_name = next(k for k in widgets.exports if k.split('.')[-1] == name)
        kind, index = widgets.exports[export_name]
        assert kind == 2
        definition = widgets.defs[index]
        frames = []
        for frame in widgets.frames[definition[1]:definition[1] + definition[2]]:
            children = []
            for node in widgets.geometry[frame['start']:frame['start'] + frame['count']]:
                typ, child = node['header'][1] & 255, node['header'][3]
                children.append(dict(name=node['name'], header=node['header'], matrix=node['matrix'],
                                     symbol=widgets.imports[child] if typ == 4 else 'local:' + str(child)))
            frames.append(dict(label=frame['label'], children=children))
        data['widgets'][name] = frames
    (assets / 'ps4_workstations.json').write_text(json.dumps(data, indent=2) + '\n')
    print('Exported', len(data['sprites']), 'original sprites and', len(data['scenes']), 'scenes')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input-dir', type=Path, required=True)
    parser.add_argument('--project-root', type=Path, required=True)
    parser.add_argument('--eboot', type=Path, required=True)
    args = parser.parse_args()
    export(args.input_dir, args.project_root, args.eboot)
