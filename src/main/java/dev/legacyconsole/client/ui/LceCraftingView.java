/** IUIScene_CraftingMenu::handleKeyDown/UpdateTooltips and ShowPanelDisplay order. */
public enum LceCraftingView {
  INVENTORY("Inventory", "Show Description"),
  DESCRIPTION("Description", "Show Ingredients"),
  INGREDIENTS("Ingredients", "Show Inventory");

  public final String title, nextLabel;
  LceCraftingView(String title, String nextLabel) { this.title = title; this.nextLabel = nextLabel; }
  public LceCraftingView next() { return values()[(ordinal() + 1) % values().length]; }

  public String[] prompts(boolean canCreate) {
    List<String> result = new ArrayList<>();
    if (canCreate) Collections.addAll(result, "cross", "Create");
    Collections.addAll(result, "circle", "Exit", "square", nextLabel,
        "left_bumper", "", "right_bumper", "Change Group");
    return result.toArray(new String[0]);
  }
}
