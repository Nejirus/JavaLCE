/** Orbis Renderer::UpdateGamma: the original unsigned-short conversion and exponent. */
public final class LceGamma {
  private LceGamma() {}

  public static int packed(int percent) {
    return (int)(Math.max(0,Math.min(100,percent))*327.68f);
  }

  public static float exponent(int percent) {
    return 1f/(packed(percent)*(1f/32768f)*1.5f+.5f);
  }
}
