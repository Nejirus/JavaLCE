/** Active PS4 Miles focus cue; the remaining cues retain their LCE XAP settings. */
final class LceUiSounds {
  private LceUiSounds() {}

  static float gain(String cue) {
    int hundredthsDb =
        cue.equals("focus") ? 0 : cue.equals("confirm") || cue.equals("open") ? -1670 : -1200;
    return (float) Math.pow(10, hundredthsDb / 2000.0);
  }

  static float pitch(String cue, Random random) {
    return cue.equals("focus") ? .943874f + random.nextFloat() * (1.059463f - .943874f) : 1;
  }
}
