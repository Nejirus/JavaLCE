/** LCE's platform loop updates music once per presented frame, targeting 60 Hz. */
final class LceAudioClock {
  private long previous, remainder;
  private boolean initialized;

  int updates(long nanos) {
    if (!initialized) {
      previous = nanos;
      initialized = true;
      return 0;
    }
    long elapsed = Math.max(0, nanos - previous);
    previous = nanos;
    // Keep console cadence independent of Java's FPS cap and monitor refresh rate.
    long scaled = remainder + Math.min(elapsed, 60_000_000_000L) * 60;
    remainder = scaled % 1_000_000_000L;
    return (int) (scaled / 1_000_000_000L);
  }
}
