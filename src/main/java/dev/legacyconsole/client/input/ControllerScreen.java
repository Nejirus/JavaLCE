public interface ControllerScreen {
  default void controllerOpened() {}

  default void controllerTick(PadState state, PadState previous) {}

  default boolean controllerPointer() {
    return false;
  }

  /** Actual holder bounds relative to the container, including its visible border. */
  default int[] controllerSlotBounds(Slot slot) {
    return new int[] {slot.x, slot.y, 16, 16};
  }

  default float[] controllerSlotBoundsExact(Slot slot) {
    int[] bounds = controllerSlotBounds(slot);
    return new float[] {bounds[0], bounds[1], bounds[2], bounds[3]};
  }

  /** Return true when the action was consumed. Direction is one of PadState.UP/DOWN/LEFT/RIGHT. */
  boolean controllerDirection(int direction);

  boolean controllerButton(int button);
}
